import {test,expect} from '@playwright/test';
test('opt-in glass preview preserves the current design and working context',async({page})=>{
 await page.goto('/?design=current');
 await expect(page.locator('html')).toHaveAttribute('data-design','current');
 const command=page.getByRole('textbox',{name:'Command',exact:true});
 await command.fill('Show remaining work');await command.press('Enter');
 await expect(page.locator('[data-issue]')).toHaveCount(8);
 const toolbar=await page.locator('.surface-toolbar').boundingBox();
 const table=await page.locator('.table-scroll').boundingBox();
 expect(toolbar?.height).toBeLessThanOrEqual(52);
 expect(Math.abs((toolbar!.y+toolbar!.height)-table!.y)).toBeLessThanOrEqual(2);
 await page.getByRole('button',{name:'Glass',exact:true}).click();
 await expect(page.locator('html')).toHaveAttribute('data-design','glass');
 await expect(page.locator('[data-issue]')).toHaveCount(8);
 await expect(command).toBeInViewport();
 await page.screenshot({path:'docs/screenshots/glass-preview/01-workspace.png'});
 await command.fill('Why is delivery at risk?');await command.press('Enter');
 await expect(page.locator('[data-issue]')).toHaveCount(2);
 await page.screenshot({path:'docs/screenshots/glass-preview/02-investigation.png'});
 await page.getByRole('button',{name:'Classic',exact:true}).click();
 await expect(page.getByTestId('risk-investigation')).toBeVisible();
 await expect(page.locator('html')).toHaveAttribute('data-design','current');
 await page.getByRole('button',{name:'Back',exact:true}).click();
 await expect(page.locator('[data-issue]')).toHaveCount(8);
 await page.goto('/?design=glass');
 await expect(page.locator('html')).toHaveAttribute('data-design','glass');
 await page.setViewportSize({width:390,height:900});
 await expect(command).toBeInViewport();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'docs/screenshots/glass-preview/03-mobile.png'});
 await page.goto('/?design=current');
 await expect(page.locator('html')).toHaveAttribute('data-design','current');
});
