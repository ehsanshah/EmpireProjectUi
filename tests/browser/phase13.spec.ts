import {expect,test} from '@playwright/test';
const base='/o/demo/p/empire';
test('People access preview, receipt, revocation and restricted lens',async({page})=>{
 await page.goto(`${base}/people?design=current`);
 await expect(page.getByRole('heading',{name:'People & access',level:1})).toBeVisible();
 await expect(page.locator('html')).toHaveAttribute('data-design','current');await expect(page.locator('html')).toHaveAttribute('data-theme','light');await expect(page.locator('.assistant')).toHaveCount(0);
 await expect(page.locator('.p13')).toContainText('Policy revision 1');
 await page.getByRole('button',{name:'Preview revoke'}).first().click();
 await expect(page.locator('.p13-card').last()).toContainText('people.read');
 await page.getByRole('button',{name:'Apply with receipt'}).click();
 await expect(page.locator('.p13-notice')).toContainText('demo-admin-receipt');
 await expect(page.locator('.p13')).toContainText('Policy revision 2');
 await page.getByRole('combobox',{name:'Demo policy lens'}).selectOption('ali-reviewer');
 await expect(page.locator('.p13-lens')).toContainText('None · restricted projection');
 await expect(page.locator('.p13-denied')).toContainText('Access unavailable');
 await expect(page.locator('.p13-table-wrap')).toHaveCount(0);
 await page.screenshot({path:'docs/screenshots/phase13-people-restricted-en.png'});
});
test('Settings draft validates, approval remains separate from publication, Back restores page',async({page})=>{
 await page.goto(`${base}/work?design=current&view=list`);
 await page.getByRole('button',{name:'Versioned settings'}).click();
 await expect(page).toHaveURL(/\/settings\?/);
 await page.getByRole('button',{name:'Create draft'}).click();
 await page.getByRole('button',{name:'Save draft revision'}).click();
 await page.getByRole('button',{name:'Validate & preview migration'}).click();
 await expect(page.locator('.p13-preview')).toContainText('Ready for approval');
 await page.getByRole('button',{name:'Approve current revision'}).click();
 await expect(page.locator('.p13-preview')).toContainText('Approved hash');
 await page.getByRole('button',{name:'Publish with receipt'}).click();
 await expect(page.locator('.p13-banner')).toContainText('Settings version 2');
 await page.getByRole('button',{name:'Back',exact:true}).click();await expect(page).toHaveURL(/\/work\?/);
 await page.goto(`${base}/settings?design=current`);
 await page.screenshot({path:'docs/screenshots/phase13-settings-en-light.png'});
});
test('Workflow errors, connections and RTL mobile remain visible and keyboard accessible',async({page})=>{
 await page.goto(`${base}/settings?design=current&section=workflow`);
 await page.getByRole('button',{name:'Create draft'}).click();
 await page.getByLabel('Required field on review → completed').fill('missing-field');
 await page.getByRole('button',{name:'Save draft revision'}).click();
 await page.getByRole('button',{name:'Validate & preview migration'}).click();
 await expect(page.locator('.p13-error')).toContainText('undefined');
 await expect(page.getByRole('button',{name:'Approve current revision'})).toBeDisabled();
 await page.getByRole('button',{name:'Connections'}).click();
 await expect(page.locator('.p13-connection')).toHaveCount(2);
 await expect(page.locator('.p13-connection').first()).toContainText('not_run');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('combobox',{name:'Language'}).selectOption('fa');
 await expect(page.locator('html')).toHaveAttribute('dir','rtl');
 expect(await page.evaluate(()=>getComputedStyle(document.documentElement).fontFamily)).toContain('Vazir');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:'docs/screenshots/phase13-connections-fa-mobile.png'});
 await page.getByRole('combobox',{name:'زبان'}).selectOption('ar');
 expect(await page.evaluate(()=>getComputedStyle(document.documentElement).fontFamily)).toContain('Empire Arabic');
 await expect(page.locator('html')).toHaveAttribute('dir','rtl');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.locator('.p13-tabs button').last().focus();await expect(page.locator('.p13-tabs button').last()).toBeFocused();
 await page.keyboard.press('Enter');await expect(page.locator('.p13-unavailable')).toHaveCount(7);
 await page.locator('.theme-toggle').click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await page.screenshot({path:'docs/screenshots/phase13-organization-ar-mobile.png'});
});
