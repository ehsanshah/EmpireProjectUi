import {expect,test} from '@playwright/test';

const base='http://127.0.0.1:5178/o/demo/p/empire';
test('Knowledge citation opens its exact version, expired ticket recovers, and revoke redacts projections',async({page})=>{
 await page.goto(`${base}/knowledge?design=current`);
 await expect(page.getByRole('heading',{name:'Knowledge',level:1})).toBeVisible();
 await expect(page.locator('.work-controls')).toBeHidden();
 await page.locator('.p11-list>button').filter({hasText:'External runbook'}).click();
 await expect(page.getByText('Source content unavailable. No preview or citation is offered.')).toBeVisible();
 await page.locator('.p11-list>button').filter({hasText:'Review working note'}).click();
 await expect(page.getByText('Stale Demo source. Verify freshness before relying on it.')).toBeVisible();
 await page.getByRole('textbox',{name:'Search this project’s knowledge'}).fill('Original review note');
 await page.locator('.p11-search').getByRole('button',{name:'Search',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Authorized matches: 1'})).toBeVisible();
 await page.locator('.p11-results button').first().click();
 await expect(page.locator('.p11-preview pre')).toContainText('Original review note');
 await expect(page.locator('.p11-preview pre')).not.toContainText('Updated review note');
 await expect(page).toHaveURL(/source=note-empire-review&version=1/);
 await page.getByRole('button',{name:'Simulate expired ticket and recover'}).click();
 await expect(page.locator('.p11-preview pre')).toContainText('Original review note');
 await page.getByRole('button',{name:'Simulate source revocation'}).click();
 await expect(page.getByRole('heading',{name:'Access revoked'})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Authorized matches: 0'})).toBeVisible();
 await expect(page.locator('.p11-preview pre')).toHaveCount(0);
 await expect(page.locator('.p11-list')).not.toContainText('Review working note');
 await page.reload();
 await expect(page.getByRole('heading',{name:'Access revoked'})).toBeVisible();
 await page.screenshot({path:'docs/screenshots/phase11-knowledge-revoked.png'});
});

test('Knowledge search, citation and Back work from keyboard; missing link has its own state',async({page})=>{
 await page.goto(`${base}/knowledge?design=current&source=missing-source&version=1`);
 await expect(page.getByRole('heading',{name:'Missing source'})).toBeVisible();
 const search=page.getByRole('textbox',{name:'Search this project’s knowledge'});
 await search.focus();
 await page.keyboard.type('Original review note');
 await page.keyboard.press('Enter');
 const hit=page.locator('.p11-results button').first();
 await hit.focus();
 await page.keyboard.press('Enter');
 await expect(page.locator('.p11-preview pre')).toContainText('Original review note');
 await page.goBack();
 await expect(page.getByRole('heading',{name:'Authorized matches: 1'})).toBeVisible();
 await page.goBack();
 await expect(page.getByRole('heading',{name:'Missing source'})).toBeVisible();
 await expect(search).toHaveValue('');
});

test('unsafe source text stays inert, project switching scopes results, and Persian mobile remains usable',async({page})=>{
 await page.goto(`${base}/knowledge?design=current`);
 await page.locator('.p11-create summary').first().click();
 await page.getByRole('textbox',{name:'Title'}).fill('Unsafe preview fixture');
 await page.getByRole('textbox',{name:'Locator'}).first().fill('fixture:unsafe#1');
 await page.getByRole('textbox',{name:'Text only'}).first().fill('<script>window.__pwned=1</script><svg onload="window.__pwned=2"></svg>');
 await page.getByRole('button',{name:'Save Demo source'}).click();
 await expect(page.locator('.p11-preview pre')).toContainText('<script>window.__pwned=1</script>');
 expect(await page.evaluate(()=>Reflect.get(window,'__pwned'))).toBeUndefined();
 await page.goto('http://127.0.0.1:5178/o/demo/p/payment/knowledge?design=current');
 await expect(page.locator('.p11-list')).not.toContainText('Unsafe preview fixture');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('combobox',{name:'Language'}).selectOption('fa');
 await page.locator('.theme-toggle').click();
 await expect(page.locator('html')).toHaveAttribute('dir','rtl');
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
 await expect(page.getByRole('heading',{name:'منابع'})).toBeVisible();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
 await page.screenshot({path:'docs/screenshots/phase11-knowledge-mobile-fa-dark.png'});
});

