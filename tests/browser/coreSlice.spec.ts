import {test,expect} from '@playwright/test';

test('Demo drawer proves receipt, activity, 412 recovery, 202 and lost-response reconciliation',async({page})=>{
 await page.goto('/?design=glass');
 await expect(page.getByTestId('result-count')).toHaveText('14');
 await page.getByRole('textbox',{name:'Command'}).fill('EMP-102');
 await page.getByRole('button',{name:'Run command'}).click();
 const drawer=page.getByRole('dialog',{name:'EMP-102'});
 await expect(drawer).toBeVisible();
 await expect(drawer.getByRole('region',{name:'Demo transition and activity'})).toContainText('DEMO CORE');
 await drawer.getByRole('combobox',{name:'EMP-102 status'}).selectOption('review');
 await expect(drawer.getByText('Applied Demo receipt')).toBeVisible();
 await expect(drawer.locator('.core-activity li')).toHaveCount(1);
 await drawer.getByRole('button',{name:'Simulate concurrent version'}).click();
 await drawer.getByRole('combobox',{name:'EMP-102 status'}).selectOption('completed');
 await expect(drawer.getByText('Version conflict — draft kept')).toBeVisible();
 await expect(drawer.getByRole('combobox',{name:'EMP-102 status'})).toHaveValue('review');
 await drawer.getByRole('button',{name:'Use latest version and retry'}).click();
 await expect(drawer.getByRole('combobox',{name:'EMP-102 status'})).toHaveValue('completed');
 await expect(drawer.locator('.core-activity li')).toHaveCount(2);
 await drawer.getByRole('combobox',{name:'Next status change'}).selectOption('async');
 await drawer.getByRole('combobox',{name:'EMP-102 status'}).selectOption('todo');
 await expect(drawer.getByRole('combobox',{name:'EMP-102 status'})).toHaveValue('todo');
 await expect(drawer.locator('.core-activity li')).toHaveCount(3);
 await drawer.getByRole('combobox',{name:'Next status change'}).selectOption('outcome_unknown');
 await drawer.getByRole('combobox',{name:'EMP-102 status'}).selectOption('review');
 await expect(drawer.getByRole('combobox',{name:'EMP-102 status'})).toHaveValue('review');
 await expect(drawer.locator('.core-activity li')).toHaveCount(4);
 await page.screenshot({path:'evidence/phase02-demo-drawer.png'});
 await drawer.getByRole('button',{name:'Close issue'}).click();
 await page.getByRole('combobox',{name:'Language'}).selectOption('fa');
 await page.getByRole('button',{name:'تغییر تم'}).click();
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('textbox',{name:'فرمان'}).fill('EMP-102');
 await page.getByRole('button',{name:'اجرای فرمان'}).click();
 const faDrawer=page.getByRole('dialog',{name:'EMP-102'});
 await expect(faDrawer.getByText('شواهد انتقال')).toBeVisible();
 await faDrawer.getByRole('combobox',{name:'EMP-102 وضعیت'}).selectOption('completed');
 await expect(faDrawer.getByText('رسید اعمال آزمایشی')).toBeVisible();
 await page.screenshot({path:'evidence/phase02-mobile-fa-light.png'});
});

test('Demo project creation records a human Owner and visible receipt once',async({page})=>{
 await page.goto('/?design=glass');
 await page.locator('.project-switch-trigger').click();
 await page.getByRole('dialog',{name:'Project browser'}).getByRole('button',{name:'New project'}).click();
 const form=page.getByTestId('new-project-form');
 await form.locator('#project-ownerId').selectOption('sara-moradi');
 await form.locator('#project-name').fill('Phase Two Review');
 await form.locator('#project-key').fill('PH2');
 await form.locator('#project-teamId').selectOption('commerce');
 await form.getByRole('button',{name:'Create project'}).click();
 await expect(form.getByText('Project created locally')).toBeVisible();
 await expect(form.getByText('Demo creation receipt')).toBeVisible();
 const stored=await page.evaluate(()=>JSON.parse(localStorage.getItem('empire-created-projects-v1:local-demo:workspace')||'[]')) as Array<{key:string;ownerId:string}>;
 expect(stored.find(project=>project.key==='PH2')?.ownerId).toBe('sara-moradi');
 await form.getByRole('button',{name:'Open project'}).click();
 await expect(page.locator('.project-switch-trigger')).toContainText('Phase Two Review');
 await expect(page.getByTestId('result-count')).toHaveText('0');
});
